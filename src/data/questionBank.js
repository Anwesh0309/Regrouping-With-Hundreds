// Simple verification helper
export function validateBank() {
  let errors = [];
  QUESTION_BANK.forEach(q => {
    if (q.type === 'true_false' || q.type === 'mixed_challenge') {
      // Checked via showSum string or correctStr
      return;
    }
    const expected = q.operation === 'add' ? q.operandA + q.operandB : q.operandA - q.operandB;
    if (q.correctAnswer !== expected && q.type !== 'missing_addend') {
      errors.push(`[${q.id}] math mismatch: ${q.operandA} ${q.operation} ${q.operandB} = expected ${expected}, got ${q.correctAnswer}`);
    }
  });
  if (errors.length > 0) {
    console.error("Question Bank Validation Errors:", errors);
  } else {
    console.log("Question Bank is 100% arithmetically valid!");
  }
}
